const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("droidProxy", {
  getSettings: () => ipcRenderer.invoke("settings:get"),
  saveSettings: (settings) => ipcRenderer.invoke("settings:save", settings),
  startProxy: () => ipcRenderer.invoke("proxy:start"),
  stopProxy: () => ipcRenderer.invoke("proxy:stop"),
  proxyState: () => ipcRenderer.invoke("proxy:state"),
  getLogs: () => ipcRenderer.invoke("logs:get"),
  login: (provider) => ipcRenderer.invoke("auth:login", provider),
  accounts: () => ipcRenderer.invoke("auth:accounts"),
  usage: (accountId) => ipcRenderer.invoke("usage:fetch", accountId),
  apiUsage: () => ipcRenderer.invoke("usage:api"),
  factoryStatus: () => ipcRenderer.invoke("factory:status"),
  applyFactory: () => ipcRenderer.invoke("factory:apply"),
  openAuthFolder: () => ipcRenderer.invoke("paths:openAuth"),
  openFactoryFolder: () => ipcRenderer.invoke("paths:openFactory"),
  routing: () => ipcRenderer.invoke("routing:get"),
  saveRouting: (routing) => ipcRenderer.invoke("routing:save", routing),
  factoryModes: () => ipcRenderer.invoke("modes:get"),
  applyFactoryModes: (choices) => ipcRenderer.invoke("modes:apply", choices),
  apiProviders: () => ipcRenderer.invoke("apikeys:list"),
  setApiKey: (entry) => ipcRenderer.invoke("apikeys:set", entry),
  clearApiKey: (provider) => ipcRenderer.invoke("apikeys:clear", provider),
  managerState: () => ipcRenderer.invoke("manager:state"),
  saveManager: (config) => ipcRenderer.invoke("manager:save", config),
  installManager: () => ipcRenderer.invoke("manager:install"),
  uninstallManager: () => ipcRenderer.invoke("manager:uninstall"),
  runRetrospective: () => ipcRenderer.invoke("manager:retro"),
  openManagerFolder: () => ipcRenderer.invoke("manager:openFolder"),
  mediaState: () => ipcRenderer.invoke("media:state"),
  setMediaKey: (apiKey) => ipcRenderer.invoke("media:setKey", apiKey),
  clearMediaKey: () => ipcRenderer.invoke("media:clearKey"),
  speak: (options) => ipcRenderer.invoke("media:speak", options),
  generateVideo: (options) => ipcRenderer.invoke("media:video", options),
  openMediaFolder: () => ipcRenderer.invoke("media:openFolder"),
  showMediaFile: (file) => ipcRenderer.invoke("media:showFile", file),
  openVeo: (options) => ipcRenderer.invoke("media:openVeo", options),
  veoState: () => ipcRenderer.invoke("media:veoState"),
  stopVeo: () => ipcRenderer.invoke("media:stopVeo"),
  onMediaCollected: (callback) => ipcRenderer.on("media:collected", (_event, item) => callback(item)),
  onVeoState: (callback) => ipcRenderer.on("media:veoState", (_event, state) => callback(state)),
  onProxyState: (callback) => ipcRenderer.on("state:proxy", (_event, state) => callback(state)),
  onLogs: (callback) => ipcRenderer.on("state:logs", (_event, logs) => callback(logs)),
  onAccountsChanged: (callback) => ipcRenderer.on("state:accountsChanged", () => callback())
});
